#!/usr/bin/env python3
"""8B (core) vs 70B (for interest) on every analysed condition; writes comparison.md.

    python interest/model-70b/compare.py
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
PAIRS = [  # (8B arm, 70B arm, condition)
    ("core_counts", "m70_core_counts", "counts_n10_cycle_full"),
    ("core_cheap_talk", "m70_core_cheap_talk", "cheap_talk_n10_cycle_full"),
    ("core_counts", "m70_core_counts_n20", "counts_n20_cycle_full"),
    ("core_cheap_talk", "m70_core_cheap_talk_n20", "cheap_talk_n20_cycle_full"),
    ("second_topology_counts", "m70_second_topology_counts", "counts_n10_complete_full"),
    ("second_topology_cheap_talk", "m70_second_topology_cheap_talk", "cheap_talk_n10_complete_full"),
]


def ci(x):
    return f"{x['mean']:.4f} [{x['lo']:.4f}, {x['hi']:.4f}]"


def row(d):
    s = d["scores"]
    crps = {k: ci(v) for k, v in s["crps"].items()}
    ferr = {k: ci(v) for k, v in s["F_error"].items()}
    xs = d["X"]["swarm"]["mean"]
    late = sum(xs[15:20]) / 5
    eps = {k: v.get("eps_swarm") for k, v in d["defects"].items()}
    return {"crps": crps, "F_error": ferr, "D": ci(s["paired_D"]) if s.get("paired_D") else None,
            "x_round1": xs[0], "x_late": late, "eps_swarm": eps,
            "consensus": d["consensus"]["swarm"]["prob"]}


def main():
    out = ["# 8B (core) vs 70B (for interest)", "",
           "Generated by `interest/model-70b/compare.py`. CRPS of the forecast of y (high bids "
           "in rounds 16-20, normalised by 5n); lower is better. F_error: swarm minus mean "
           "forecast (negative: the audit predicts too many high bids). D: paired CRPS(actions-only) "
           "minus CRPS(signal-aware); positive favours the signal-aware audit. 95% intervals "
           "from 2,000 resamples of whole runs.", ""]
    res = {}
    for a8, a70, cond in PAIRS:
        p8 = REPO / "results" / "analysis" / a8 / f"{cond}.json"
        p70 = HERE / "analysis" / a70 / f"{cond}.json"
        if not (p8.exists() and p70.exists()):
            continue
        r8, r70 = row(json.loads(p8.read_text())), row(json.loads(p70.read_text()))
        res[cond] = {"8B": r8, "70B": r70}
        out += [f"## {cond}", "", "| | 8B | 70B |", "|---|---|---|"]
        for k in r8["crps"]:
            out.append(f"| CRPS {k} | {r8['crps'][k]} | {r70['crps'][k]} |")
        for k in r8["F_error"]:
            out.append(f"| F_error {k} | {r8['F_error'][k]} | {r70['F_error'][k]} |")
        if r8["D"]:
            out.append(f"| D | {r8['D']} | {r70['D']} |")
        out.append(f"| share H, round 1 | {r8['x_round1']:.3f} | {r70['x_round1']:.3f} |")
        out.append(f"| share H, rounds 16-20 | {r8['x_late']:.3f} | {r70['x_late']:.3f} |")
        for k in r8["eps_swarm"]:
            out.append(f"| ε_swarm {k} | {r8['eps_swarm'][k]:.3f} | {r70['eps_swarm'][k]:.3f} |")
        c8, c70 = r8["consensus"], r70["consensus"]
        out.append(f"| consensus H / L / none | {c8['H']:.2f} / {c8['L']:.2f} / {c8['']:.2f} | "
                   f"{c70['H']:.2f} / {c70['L']:.2f} / {c70['']:.2f} |")
        out.append("")
    (HERE / "comparison.md").write_text("\n".join(out) + "\n")
    (HERE / "comparison.json").write_text(json.dumps(res, indent=1) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
